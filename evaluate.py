def _mirror(square: int) -> int:
    """Flip a square vertically (for looking up Black's PST value using
    the same White-oriented table)."""
    return square ^ 56


def evaluate(board: Board) -> int:
    """Static evaluation from White's perspective, in centipawns."""
    score = 0
    for piece, value in PIECE_VALUES.items():
        w_bb = board.bb[WHITE][piece]
        b_bb = board.bb[BLACK][piece]
        pst = PST[piece]
        score += value * w_bb.bit_count()
        score -= value * b_bb.bit_count()
        for s in iter_bits(w_bb):
            score += pst[s]
        for s in iter_bits(b_bb):
            score -= pst[_mirror(s)]
    return score
